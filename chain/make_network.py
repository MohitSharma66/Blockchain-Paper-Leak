#!/usr/bin/env python3
"""
make_network.py - generate a private Hyperledger Besu QBFT network for the
NEET Integrity Chain (one PC, many Docker containers, one container per node).

What it writes (default: ./chain/network/):
  genesis.json                QBFT genesis; the initial validators are in extraData
  keys/<node>/key             node private key (hex). TEST KEYS ONLY - never reuse
  nodes.json                  name, validator address, enode, static IP, host RPC port
  docker-compose.chain.yml    one Besu service per node on a fixed-IP bridge network
  docker-compose.apps.yml     override for YOUR compose.yaml: backend + printers
                              get CHAIN_RPC_URL, zero funding, and join the chain network

Run it from the project root (the folder that holds compose.yaml):
    python chain/make_network.py --centers 6

Every node is a validator at the start (board node + N center nodes).  Validators
can later be added/removed by vote - see chainctl.py.

Needs only the Python packages already in backend/requirements.txt (eth-keys via web3).
"""
from __future__ import annotations

import argparse
import ipaddress
import json
import os
import re
import secrets
import shutil
import sys
from pathlib import Path

try:
    from eth_keys import keys as eth_keys
except ImportError:  # pragma: no cover
    sys.exit("eth-keys is missing. Run: pip install web3   (it pulls eth-keys in)")

# Besu's QBFT mixHash constant ("Istanbul byzantine fault tolerance" as ASCII).
QBFT_MIX_HASH = "0x63746963616c2062797a616e74696e65206661756c7420746f6c6572616e6365"


# ---------------------------------------------------------------- tiny RLP
def _rlp_len(n: int, offset: int) -> bytes:
    if n < 56:
        return bytes([offset + n])
    b = n.to_bytes((n.bit_length() + 7) // 8, "big")
    return bytes([offset + 55 + len(b)]) + b


def rlp_encode(x) -> bytes:
    if isinstance(x, (bytes, bytearray)):
        x = bytes(x)
        if len(x) == 1 and x[0] < 0x80:
            return x
        return _rlp_len(len(x), 0x80) + x
    if isinstance(x, (list, tuple)):
        body = b"".join(rlp_encode(i) for i in x)
        return _rlp_len(len(body), 0xC0) + body
    raise TypeError(type(x))


def qbft_extra_data(validators: list[str]) -> str:
    """RLP[ vanity(32B), [validator addrs], vote(EMPTY LIST for QBFT; IBFT2 uses empty bytes), round(integer 0 = empty, no leading zeros), seals[] ]"""
    addrs = sorted(bytes.fromhex(v[2:]) for v in validators)
    payload = [b"\x00" * 32, addrs, [], b"", []]
    return "0x" + rlp_encode(payload).hex()


# ---------------------------------------------------------------- nodes
def make_node(name: str, ip: str, rpc_port: int) -> dict:
    priv = eth_keys.PrivateKey(secrets.token_bytes(32))
    pub = priv.public_key
    return {
        "name": name,
        "ip": ip,
        "rpc_port": rpc_port,
        "private_key": "0x" + priv.to_bytes().hex(),
        "address": pub.to_checksum_address().lower(),   # validator address
        "pubkey": pub.to_bytes().hex(),                 # 64 bytes, for the enode
        "enode": f"enode://{pub.to_bytes().hex()}@{ip}:30303",
    }


def build_nodes(centers: int, subnet: str, base_rpc_port: int) -> list[dict]:
    net = ipaddress.ip_network(subnet)
    hosts = list(net.hosts())
    if len(hosts) < centers + 12:
        sys.exit(f"subnet {subnet} is too small for {centers} centers")
    # .10 = board node, .11.. = centers (leaves .1 for the Docker gateway)
    first = 9
    nodes = [make_node("node-board", str(hosts[first]), base_rpc_port)]
    for i in range(1, centers + 1):
        nodes.append(make_node(f"node-center-{i:03d}", str(hosts[first + i]), base_rpc_port + i))
    return nodes


def genesis_json(chain_id: int, nodes: list[dict], block_seconds: int, alloc: dict) -> dict:
    return {
        "config": {
            "chainId": chain_id,
            "berlinBlock": 0,
            "londonBlock": 0,          # EIP-1559 tx format; base fee forced to 0 below
            "zeroBaseFee": True,       # free gas: nobody needs ETH
            "qbft": {
                "blockperiodseconds": block_seconds,
                "epochlength": 30000,
                "requesttimeoutseconds": max(4, block_seconds * 2),
            },
        },
        "nonce": "0x0",
        "timestamp": "0x58ee40ba",
        "gasLimit": "0x1fffffffffffff",
        "difficulty": "0x1",
        "mixHash": QBFT_MIX_HASH,
        "coinbase": "0x0000000000000000000000000000000000000000",
        "alloc": alloc,
        "extraData": qbft_extra_data([n["address"] for n in nodes]),
    }


# ---------------------------------------------------------------- compose (written by hand: no YAML dep)
def chain_compose(nodes: list[dict], subnet: str, rel_out: str, chain_id: int) -> str:
    board = nodes[0]
    L = [
        "# GENERATED by chain/make_network.py - do not edit, regenerate instead.",
        "# Always run from the project root:",
        "#   docker compose --project-directory . -f compose.yaml \\",
        "#       -f chain/network/docker-compose.chain.yml -f chain/network/docker-compose.apps.yml up -d",
        "",
        "x-besu: &besu",
        "  image: ${BESU_IMAGE:-hyperledger/besu:latest}",
        "  restart: unless-stopped",
        "  environment:",
        "    BESU_OPTS: ${BESU_OPTS:--Xmx512m}",
        "",
        "services:",
    ]
    for n in nodes:
        cmd = [
            "--data-path=/data",
            "--genesis-file=/config/genesis.json",
            "--node-private-key-file=/config/key",
            f"--network-id={chain_id}",
            f"--p2p-host={n['ip']}",
            "--p2p-port=30303",
            "--nat-method=NONE",
            "--min-gas-price=0",
            "--revert-reason-enabled",
            "--rpc-http-enabled",
            "--rpc-http-host=0.0.0.0",
            "--rpc-http-port=8545",
            "--rpc-http-api=ETH,NET,QBFT,WEB3,TXPOOL,ADMIN",
            "--host-allowlist=*",
            "--rpc-http-cors-origins=*",
            "--logging=INFO",
        ]
        if n is not board:
            cmd.append(f"--bootnodes={board['enode']}")
        L += [
            f"  {n['name']}:",
            "    <<: *besu",
            f"    container_name: neet-{n['name']}",
            "    command:",
            *[f'      - "{c}"' for c in cmd],
            "    volumes:",
            f"      - ./{rel_out}/keys/{n['name']}/key:/config/key:ro",
            f"      - ./{rel_out}/genesis.json:/config/genesis.json:ro",
            f"      - data_{n['name'].replace('-', '_')}:/data",
            "    ports:",
            f'      - "127.0.0.1:{n["rpc_port"]}:8545"',
            "    networks:",
            "      neetchain:",
            f"        ipv4_address: {n['ip']}",
            "",
        ]
    L += ["networks:", "  neetchain:", "    driver: bridge", "    ipam:", "      config:",
          f"        - subnet: {subnet}", "", "volumes:"]
    L += [f"  data_{n['name'].replace('-', '_')}:" for n in nodes]
    return "\n".join(L) + "\n"


def apps_compose(base_compose: Path, nodes: list[dict], board_url: str) -> tuple[str, list[str]]:
    """Override for the user's compose.yaml. Returns (yaml_text, warnings)."""
    import yaml  # PyYAML ships with the backend deps; only needed here
    warns: list[str] = []
    base = yaml.safe_load(base_compose.read_text(encoding="utf-8")) or {}
    services = base.get("services", {})
    by_center = {n["name"]: n for n in nodes}
    L = [
        "# GENERATED by chain/make_network.py - points the apps at the private chain.",
        "services:",
        "  backend:",
        "    environment:",
        f"      CHAIN_RPC_URL: {board_url}",
        '      PRINTER_FUNDING_ETH: "0"',
        "    networks: [default, neetchain]",
    ]
    for svc, spec in services.items():
        m = re.fullmatch(r"printer-center-(\d{3})", svc)
        if not m:
            continue
        node = by_center.get(f"node-center-{m.group(1)}")
        if node is None:
            warns.append(f"{svc}: no chain node node-center-{m.group(1)} (raise --centers); "
                         f"it keeps its old RPC and will not work on the private chain")
            continue
        url = f"http://{node['name']}:8545"
        L += [f"  {svc}:", "    environment:", f"      CHAIN_RPC_URL: {url}", f"      RPC_URL: {url}",
              "    networks: [default, neetchain]"]
        cmd = spec.get("command")
        if isinstance(cmd, list) and "--rpc-url" in cmd:
            cmd = list(cmd)
            cmd[cmd.index("--rpc-url") + 1] = url
            L.append("    command:")
            L += [f"      - {json.dumps(str(c))}" for c in cmd]
        else:
            warns.append(f"{svc}: no list-style command with --rpc-url found; set --rpc-url {url} yourself")
    L.append("")
    if "printer-center-generic" in services:
        # Used by scripts/new-printer.cmd, which overrides CHAIN_RPC_URL with the new center's own node.
        L += ["  printer-center-generic:", "    environment:",
              f"      CHAIN_RPC_URL: {board_url}", f"      RPC_URL: {board_url}",
              "    networks: [default, neetchain]"]
    return "\n".join(L), warns


# ---------------------------------------------------------------- main
def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--centers", type=int, default=6, help="center nodes besides the board node (default 6 -> 7 validators)")
    ap.add_argument("--committee", type=int, default=None,
                    help="how many centers start as validators (default: all). The other centers still run a node "
                         "that syncs and verifies every block, they just do not vote until `chainctl.py rotate` adds them.")
    ap.add_argument("--chain-id", type=int, default=7357)
    ap.add_argument("--subnet", default="172.30.0.0/24")
    ap.add_argument("--block-seconds", type=int, default=2)
    ap.add_argument("--base-rpc-port", type=int, default=8545, help="board node RPC on this host port, centers on +1, +2...")
    ap.add_argument("--out", default="chain/network")
    ap.add_argument("--base-compose", default="compose.yaml", help="your existing compose file (for the apps override)")
    ap.add_argument("--force", action="store_true", help="overwrite an existing network (NEW keys, NEW genesis -> wipe old volumes)")
    a = ap.parse_args()

    if a.centers < 3:
        sys.exit("QBFT needs at least 4 validators to tolerate even one fault: use --centers 3 or more")
    root = Path.cwd()
    out = (root / a.out).resolve()
    if out.exists() and any(out.iterdir()):
        if not a.force:
            sys.exit(f"{a.out} already exists. Re-running would change every key and the genesis. Use --force "
                     f"(then run: docker compose ... down -v to drop the old chain data).")
        shutil.rmtree(out)
    rel_out = os.path.relpath(out, root).replace("\\", "/")

    nodes = build_nodes(a.centers, a.subnet, a.base_rpc_port)
    committee = a.centers if a.committee is None else a.committee
    if not 0 < committee <= a.centers:
        sys.exit("--committee must be between 1 and --centers")
    if committee + 1 < 4:
        sys.exit("QBFT needs at least 4 validators (board + 3 centers) to tolerate even one fault")
    validators = nodes[: committee + 1]          # board node + the first N centers
    for n in nodes:
        kd = out / "keys" / n["name"]
        kd.mkdir(parents=True, exist_ok=True)
        (kd / "key").write_text(n["private_key"][2:] + "\n")  # bare hex, no 0x
    (out / "genesis.json").write_text(json.dumps(genesis_json(a.chain_id, validators, a.block_seconds, {}), indent=2))
    public = [{k: v for k, v in n.items() if k not in ("private_key",)} for n in nodes]
    (out / "nodes.json").write_text(json.dumps({"chain_id": a.chain_id, "subnet": a.subnet, "nodes": public}, indent=2))
    (out / "docker-compose.chain.yml").write_text(chain_compose(nodes, a.subnet, rel_out, a.chain_id))

    warns: list[str] = []
    base = root / a.base_compose
    if base.exists():
        txt, warns = apps_compose(base, nodes, f"http://{nodes[0]['name']}:8545")
        (out / "docker-compose.apps.yml").write_text(txt)
    else:
        warns.append(f"{a.base_compose} not found - apps override not written (run from the project root)")

    print(f"Wrote {rel_out}/ : {len(nodes)} nodes, {len(validators)} of them validators "
          f"(board + {committee} centers), chain id {a.chain_id}")
    print(f"  board RPC: http://127.0.0.1:{a.base_rpc_port}   (center RPCs: +1 ... +{a.centers})")
    for w in warns:
        print("  WARNING:", w)
    print("Next: python chain/chainctl.py up")


if __name__ == "__main__":
    main()